const assert = require('node:assert/strict');
const {fixture, tick} = require('./resume_embedded.dom.js');
const f = fixture('index.html');
f.context.clearInterval = () => {}; f.context.setInterval = () => 1;
const all = node => [node, ...node.children.flatMap(all)];
const create = f.document.createElement;
f.document.createElement = tag => {
  const node = create(tag);
  node.reportValidity = () => true;
  node.prepend = (...nodes) => { nodes.forEach(n => { n.parentElement = node; }); node.children.unshift(...nodes); };
  node.querySelectorAll = selector => all(node).slice(1).filter(n => selector.split(',').some(part => {
    if (part.startsWith('.')) return (n.className || '').split(' ').includes(part.slice(1));
    const form = part.match(/^form\[data-profile-form="(.+)"\]$/);
    return form ? n.tagName === 'FORM' && n.dataset.profileForm === form[1] : n.tagName === part.toUpperCase();
  }));
  node.querySelector = selector => node.querySelectorAll(selector)[0] || null;
  node.classList.add = name => { node.className = (node.className || '') + ' ' + name; };
  Object.defineProperty(node, 'innerHTML', {set() { throw new Error('private content must remain text'); }});
  return node;
};
const copies = [], requests = [];
f.context.navigator = {clipboard: {writeText: async text => copies.push(text)}};
const prompt = 'API 提供的导出提示词 <script>仅作为文本</script>';
const pasted = '```json\n[{"evidence":"uncertain: 合成依据"}]\n```';
let promptFails = true, importFails = true, release;
const response = (body, status = 200) => ({ok: status < 400, status, headers: {get: () => ''}, json: async () => body});
f.context.fetch = async (url, options = {}) => {
  requests.push({url, options});
  assert.equal(options.credentials, 'same-origin');
  if (url === '/api/account/me') return response({authenticated: true, login_available: true});
  if (url === '/api/profile') return response({revision: 1, facts: [], conflicts: []});
  if (url === '/api/account/mcp/inbox') return response({items: [{id: 'new', ...{category:'project',subject:'合成项目',field:'description',value:'合成动作',evidence:'合成依据'}}], pending_count: 1});
  if (url.endsWith('/prompt')) return promptFails ? response({}, 503) : response({prompt, max_chars: 100000, max_facts: 200});
  if (url === '/api/profile/import-memory') {
    assert.equal(options.method, 'POST'); assert.deepEqual(JSON.parse(options.body), {text: pasted});
    if (importFails) return response({detail: {message: '整理暂不可用'}}, 503);
    return new Promise(resolve => { release = () => resolve(response({added_count: 2, conflict_count: 1, uncertain_count: 1, duplicate_count: 1, warnings: ['已截断，请分批导入。']})); });
  }
  throw new Error('unexpected route ' + url);
};
